// Command tasks turns the last parity run into parity/TASKS.md: the failing
// lazygit tests grouped into features, biggest first.
//
//	go run ./parity/tasks                    # regenerate TASKS.md, parity/task-tests/<id>.txt and parity/STATUS.md
//	go run ./parity/tasks -show <run.json>   # print each failure in a run, with its screen
//
// A failing test belongs to the first rule in parity/TASKS.rules that matches
// its first failure ("<message>\nafter: <key> in <view>"). Failures no rule
// matches are grouped automatically by the key that didn't do what lazygit
// does, or by their message. Tasks logged as skipped in parity/LOG.md go to
// the bottom.
package main

import (
	"bufio"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"reflect"
	"regexp"
	"sort"
	"strings"

	"github.com/jesseduffield/lazygit/pkg/config"
)

type result struct {
	Name     string  `json:"name"`
	Status   string  `json:"status"`
	Reason   string  `json:"reason"`
	After    string  `json:"after"`
	Screen   string  `json:"screen"`
	Stopped  string  `json:"stopped"`
	Progress float64 `json:"progress"`
}

type rule struct {
	id, title   string
	label       string
	match       *regexp.Regexp
	port, notes []string
}

type task struct {
	id, title   string
	label       string
	port, notes []string
	tests       []result
	skipped     string
}

const dir = "parity"

func main() {
	show := flag.String("show", "", "print the failures in this run file")
	flag.Parse()
	if *show != "" {
		printFailures(*show)
		return
	}
	results := readRun(filepath.Join(dir, "last-run.json"))
	rules := readRules(filepath.Join(dir, "TASKS.rules"))
	skipped := readSkipped(filepath.Join(dir, "LOG.md"))

	tasks := map[string]*task{}
	var order []string
	add := func(id, title, label string, port, notes []string, r result) {
		t := tasks[id]
		if t == nil {
			t = &task{id: id, title: title, label: label, port: port, notes: notes, skipped: skipped[id]}
			tasks[id] = t
			order = append(order, id)
		}
		t.tests = append(t.tests, r)
	}
	var pass, fail, harness int
	var blocked []result
	for _, r := range results {
		switch r.Status {
		case "pass":
			pass++
			continue
		case "unreachable":
			harness++
			blocked = append(blocked, r)
			continue
		case "fail":
			fail++
		default:
			continue
		}
		subject := firstLine(r.Reason) + "\nafter: " + r.After
		matched := false
		for _, ru := range rules {
			if ru.match.MatchString(subject) {
				add(ru.id, ru.title, ru.label, ru.port, ru.notes, r)
				matched = true
				break
			}
		}
		if !matched {
			id, title, port := autoTask(r)
			add(id, title, "", port, nil, r)
		}
	}

	list := make([]*task, 0, len(tasks))
	for _, id := range order {
		list = append(list, tasks[id])
	}
	sort.SliceStable(list, func(i, j int) bool {
		if (list[i].skipped == "") != (list[j].skipped == "") {
			return list[i].skipped == ""
		}
		return len(list[i].tests) > len(list[j].tests)
	})

	check(os.MkdirAll(filepath.Join(dir, "task-tests"), 0o755))
	old, _ := filepath.Glob(filepath.Join(dir, "task-tests", "*.txt"))
	for _, f := range old {
		os.Remove(f)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# Parity tasks\n\nGenerated by `go run ./parity/tasks` from the last full parity run; do not edit by hand\n"+
		"(change parity/TASKS.rules instead). %d pass, %d fail, %d need harness support.\n\n"+
		"Work top-down. Each task lists the lazygit tests it should make pass (with their first failure),\n"+
		"where to port from, and how to run them: `parity/run.sh task <id>`.\n\n", pass, fail, harness)
	for i, t := range list {
		var names []string
		for _, r := range t.tests {
			names = append(names, r.Name)
		}
		check(os.WriteFile(filepath.Join(dir, "task-tests", t.id+".txt"), []byte(strings.Join(names, "\n")+"\n"), 0o644))
		fmt.Fprintf(&b, "## %d. `%s`: %s (%d tests)\n\n", i+1, t.id, t.title, len(t.tests))
		if t.skipped != "" {
			fmt.Fprintf(&b, "**Skipped earlier:** %s\n\n", t.skipped)
		}
		for _, p := range t.port {
			fmt.Fprintf(&b, "- Port from: %s\n", p)
		}
		for _, n := range t.notes {
			fmt.Fprintf(&b, "- Note: %s\n", n)
		}
		b.WriteString("- Specs (in the lazygit module, `go list -m -f '{{.Dir}}' github.com/jesseduffield/lazygit`):\n")
		for _, r := range t.tests {
			fmt.Fprintf(&b, "  - `pkg/integration/tests/%s.go`: %s", r.Name, oneLine(clarify(firstLine(r.Reason)), 140))
			if r.After != "" {
				fmt.Fprintf(&b, " (after `%s`)", r.After)
			}
			b.WriteString("\n")
		}
		b.WriteString("\n")
	}
	if len(blocked) > 0 {
		b.WriteString("## Needs harness support (not for the feature agent)\n\n")
		for _, r := range blocked {
			why := r.Stopped
			if strings.HasPrefix(r.Reason, "harness: ") {
				why = r.Reason
			}
			fmt.Fprintf(&b, "- `%s`: %s\n", r.Name, oneLine(firstLine(why), 110))
		}
	}
	check(os.WriteFile(filepath.Join(dir, "TASKS.md"), []byte(b.String()), 0o644))
	writeParityStatus(filepath.Join(dir, "STATUS.md"), results, list)
	fmt.Printf("parity/TASKS.md: %d tasks; %d pass, %d fail, %d need harness support\n", len(list), pass, fail, harness)
}

const (
	statusBegin = "<!-- parity:begin (generated by go run ./parity/tasks; do not edit) -->"
	statusEnd   = "<!-- parity:end -->"
	testsURL    = "https://github.com/jesseduffield/lazygit/tree/master/pkg/integration/tests/"
)

type area struct {
	name        string
	pass, total int
	reached     float64 // passing tests count 1, others how far they got
	blockers    map[*task]int
	harness     int // tests stopped by the harness, not the app
}

// writeParityStatus replaces the parity report's generated section with how far each of
// lazygit's test areas gets against the app, and what stops it.
func writeParityStatus(path string, results []result, tasks []*task) {
	b, err := os.ReadFile(path)
	check(err)
	head, rest, ok := strings.Cut(string(b), statusBegin)
	_, tail, ok2 := strings.Cut(rest, statusEnd)
	if !ok || !ok2 {
		fail("%s: no %q … %q section", path, statusBegin, statusEnd)
	}
	owner := map[string]*task{}
	for _, t := range tasks {
		for _, r := range t.tests {
			owner[r.Name] = t
		}
	}
	areas := map[string]*area{}
	var all area
	for _, r := range results {
		if r.Status != "pass" && r.Status != "fail" && r.Status != "unreachable" {
			continue
		}
		name, _, _ := strings.Cut(r.Name, "/")
		a := areas[name]
		if a == nil {
			a = &area{name: name, blockers: map[*task]int{}}
			areas[name] = a
		}
		for _, x := range []*area{a, &all} {
			x.total++
			if r.Status == "pass" {
				x.pass++
				x.reached++
			} else {
				x.reached += min(max(r.Progress, 0), 1)
			}
		}
		if t := owner[r.Name]; t != nil {
			a.blockers[t]++
		} else if r.Status == "unreachable" {
			a.harness++
		}
	}
	list := make([]*area, 0, len(areas))
	for _, a := range areas {
		list = append(list, a)
	}
	sort.Slice(list, func(i, j int) bool {
		si, sj := float64(list[i].pass)/float64(list[i].total), float64(list[j].pass)/float64(list[j].total)
		if si != sj {
			return si > sj
		}
		if list[i].reached/float64(list[i].total) != list[j].reached/float64(list[j].total) {
			return list[i].reached/float64(list[i].total) > list[j].reached/float64(list[j].total)
		}
		return list[i].name < list[j].name
	})

	var s strings.Builder
	s.WriteString(statusBegin + "\n\n")
	fmt.Fprintf(&s, "**%d of %d** of lazygit's own integration tests pass against laziergit (%.0f%%), and %.0f%% of all their steps\n"+
		"already behave exactly like lazygit. Every failing test is a bug; [parity/TASKS.md](TASKS.md) lists them as tasks, biggest first.\n\n",
		all.pass, all.total, pct(float64(all.pass), all.total), pct(all.reached, all.total))
	s.WriteString("`█` tests that pass · `▒` steps reached by the tests that don't yet · `░` steps still to go\n\n")
	s.WriteString("| lazygit test area | Pass | Parity | Most of the rest stop at |\n| --- | ---: | --- | --- |\n")
	for _, a := range list {
		fmt.Fprintf(&s, "| [%s](%s%s) | %d / %d | `%s` | %s |\n", humanize(a.name), testsURL, a.name, a.pass, a.total, bar(a), blockers(a))
	}
	fmt.Fprintf(&s, "\nRegenerated by `parity/run.sh all`. Areas are lazygit's `pkg/integration/tests` folders; the \"stop at\" column names the\n"+
		"[tasks](TASKS.md) holding back most of an area's failing tests, with how many each holds back.\n\n")
	s.WriteString(statusEnd)
	check(os.WriteFile(path, []byte(head+s.String()+tail), 0o644))
}

func pct(n float64, total int) float64 { return 100 * n / float64(total) }

// bar draws an area's parity in 12 cells: passing tests, then the steps the
// failing tests got through, then what is left.
func bar(a *area) string {
	const cells = 12
	full := int(float64(a.pass)/float64(a.total)*cells + 0.5)
	if a.pass > 0 && full == 0 {
		full = 1
	}
	reached := int(a.reached/float64(a.total)*cells+0.5) - full
	if reached < 0 {
		reached = 0
	}
	return strings.Repeat("█", full) + strings.Repeat("▒", reached) + strings.Repeat("░", max(cells-full-reached, 0))
}

func blockers(a *area) string {
	if a.pass == a.total {
		return "—"
	}
	counts := map[string]int{}
	if a.harness > 0 {
		counts["test harness support"] = a.harness
	}
	for t, n := range a.blockers {
		counts[taskLabel(t)] += n
	}
	labels := make([]string, 0, len(counts))
	for l := range counts {
		labels = append(labels, l)
	}
	sort.Slice(labels, func(i, j int) bool {
		if counts[labels[i]] != counts[labels[j]] {
			return counts[labels[i]] > counts[labels[j]]
		}
		return labels[i] < labels[j]
	})
	var out []string
	for _, l := range labels[:min(3, len(labels))] {
		out = append(out, fmt.Sprintf("%s (%d)", l, counts[l]))
	}
	return strings.Join(out, " · ")
}

var opens = regexp.MustCompile(`should open the (.+?), as in lazygit`)

// taskLabel names a task for a reader of the parity report: a rule's label, or for
// an automatic group the key and what lazygit opens with it.
func taskLabel(t *task) string {
	if t.label != "" {
		return t.label
	}
	key, view, _ := strings.Cut(t.tests[0].After, " in ")
	switch {
	case strings.HasPrefix(t.id, "key-") && key != "":
		if action := lazygitKeyAction(key, view); action != "" {
			return fmt.Sprintf("%s (`%s`)", action, key)
		}
		if m := opens.FindStringSubmatch(t.title); m != nil {
			return fmt.Sprintf("`%s` in %s → %s", key, view, m[1])
		}
		return fmt.Sprintf("`%s` in %s", key, view)
	case key != "":
		return fmt.Sprintf("screen after `%s` in %s", key, view)
	}
	return "first screen"
}

var cheatsheet map[string]map[string]string // section → key → action

// lazygitKeyAction is what lazygit's keybindings cheatsheet says key does in
// view, in lazygit's own words.
func lazygitKeyAction(key, view string) string {
	if cheatsheet == nil {
		cheatsheet = map[string]map[string]string{}
		out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "github.com/jesseduffield/lazygit").Output()
		if err != nil {
			return ""
		}
		b, err := os.ReadFile(filepath.Join(strings.TrimSpace(string(out)), "docs", "keybindings", "Keybindings_en.md"))
		if err != nil {
			return ""
		}
		section := ""
		for _, l := range strings.Split(string(b), "\n") {
			if h, ok := strings.CutPrefix(l, "## "); ok {
				section = h
				cheatsheet[section] = map[string]string{}
				continue
			}
			cells := strings.Split(l, " | ")
			if section == "" || len(cells) < 2 || !strings.HasPrefix(cells[0], "| `` ") {
				continue
			}
			keys := strings.TrimSuffix(strings.TrimPrefix(cells[0], "| `` "), " ``")
			keys, _, _ = strings.Cut(keys, " (")
			for _, k := range strings.Split(keys, ", ") {
				if _, seen := cheatsheet[section][k]; !seen {
					cheatsheet[section][k] = cells[1]
				}
			}
		}
	}
	sections := map[string]string{
		"files": "Files", "localBranches": "Local branches", "remotes": "Remotes", "remoteBranches": "Remote branches",
		"tags": "Tags", "commits": "Commits", "reflogCommits": "Reflog", "subCommits": "Sub-commits",
		"commitFiles": "Commit files", "stash": "Stash", "worktrees": "Worktrees", "submodules": "Submodules",
		"status": "Status", "main": "Main panel (normal)", "secondary": "Secondary",
		"commitMessage": "Commit summary", "prompt": "Input prompt", "confirmation": "Confirmation panel",
	}
	for _, sec := range []string{sections[view], "Global keybindings"} {
		if a := cheatsheet[sec][key]; a != "" {
			return a
		}
	}
	return ""
}

func humanize(s string) string {
	if s == "ui" {
		return "UI"
	}
	s = strings.ReplaceAll(s, "_", " ")
	return strings.ToUpper(s[:1]) + s[1:]
}

var (
	focusFail = regexp.MustCompile(`^Expected (.+?) to be focused|Unexpected view focused\. Expected (\w+), got`)
	quoted    = regexp.MustCompile(`'[^']*'`)
	number    = regexp.MustCompile(`\b\d+\b`)
	nonWord   = regexp.MustCompile(`[^a-z0-9]+`)
)

// autoTask groups a failure no rule covers: a key that didn't open what it
// opens in lazygit, or else the shape of the failed check.
func autoTask(r result) (id, title string, port []string) {
	msg := firstLine(r.Reason)
	key, view, _ := strings.Cut(r.After, " in ")
	if m := focusFail.FindStringSubmatch(msg); m != nil && key != "" {
		want := m[1]
		if want == "" {
			want = m[2] + " view"
		}
		id = "key-" + slug(key+"-"+view)
		title = fmt.Sprintf("`%s` in %s should open the %s, as in lazygit", key, view, want)
		if actions := lazygitActions(key, view); len(actions) > 0 {
			port = []string{"lazygit binds `" + key + "` here to " + strings.Join(actions, ", ") +
				" (pkg/config/user_config.go); find its handler in pkg/gui/controllers"}
		}
		return id, title, port
	}
	shape := number.ReplaceAllString(quoted.ReplaceAllString(msg, "'…'"), "N")
	if len(shape) > 80 {
		shape = shape[:80]
	}
	id = "check-" + slug(shape)
	if len(id) > 60 {
		id = id[:60]
	}
	if key != "" {
		title = fmt.Sprintf("after `%s` in %s: %s", key, view, shape)
	} else {
		title = shape
	}
	return strings.TrimRight(id, "-"), title, nil
}

func slug(s string) string {
	s = strings.NewReplacer("<", "", ">", "", "+", "-", " ", "-").Replace(strings.ToLower(s))
	return strings.Trim(nonWord.ReplaceAllString(s, "-"), "-")
}

// lazygitActions lists the default keybinding names lazygit gives key in the
// sections that apply to view.
func lazygitActions(key, view string) []string {
	kb := config.GetDefaultConfig().Keybinding
	sections := map[string][]string{
		"files": {"Files"}, "worktrees": {}, "submodules": {"Submodules"},
		"localBranches": {"Branches"}, "remotes": {"Branches"}, "tags": {"Branches"}, "remoteBranches": {"Branches"},
		"commits": {"Commits"}, "reflogCommits": {"Commits"}, "subCommits": {"Commits"},
		"commitFiles": {"CommitFiles"}, "stash": {"Stash"}, "main": {"Main"}, "secondary": {"Main"},
		"status": {"Status"}, "commitMessage": {"CommitMessage"}, "commitDescription": {"CommitMessage"},
	}[view]
	sections = append(sections, "Universal")
	var out []string
	root := reflect.ValueOf(kb)
	for _, sec := range sections {
		v := root.FieldByName(sec)
		if !v.IsValid() {
			continue
		}
		for i := 0; i < v.NumField(); i++ {
			kbv, ok := v.Field(i).Interface().(config.Keybinding)
			if !ok {
				continue
			}
			for _, k := range kbv {
				if k == key {
					out = append(out, strings.ToLower(sec[:1])+sec[1:]+"."+lowerFirst(v.Type().Field(i).Name))
				}
			}
		}
	}
	return out
}

func lowerFirst(s string) string { return strings.ToLower(s[:1]) + s[1:] }

func readRun(path string) []result {
	b, err := os.ReadFile(path)
	if err != nil {
		fail("no %s; run a full parity run first (parity/run.sh all)", path)
	}
	var rs []result
	check(json.Unmarshal(b, &rs))
	return rs
}

// readRules parses TASKS.rules: blocks of
//
//	[id] title
//	match: <regexp on "first failure\nafter: key in view">
//	port: <where in lazygit to port from>   (repeatable)
//	note: <anything the agent should know>  (repeatable)
//	label: <a few words for the parity table> (optional)
func readRules(path string) []rule {
	f, err := os.Open(path)
	check(err)
	defer f.Close()
	var rules []rule
	sc := bufio.NewScanner(f)
	for n := 1; sc.Scan(); n++ {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if strings.HasPrefix(line, "[") {
			id, title, ok := strings.Cut(line[1:], "]")
			if !ok {
				fail("%s:%d: want [id] title", path, n)
			}
			rules = append(rules, rule{id: id, title: strings.TrimSpace(title)})
			continue
		}
		if len(rules) == 0 {
			fail("%s:%d: field before any [id]", path, n)
		}
		r := &rules[len(rules)-1]
		k, v, _ := strings.Cut(line, ":")
		v = strings.TrimSpace(v)
		switch k {
		case "match":
			re, err := regexp.Compile(v)
			if err != nil {
				fail("%s:%d: %v", path, n, err)
			}
			r.match = re
		case "port":
			r.port = append(r.port, v)
		case "note":
			r.notes = append(r.notes, v)
		case "label":
			r.label = v
		default:
			fail("%s:%d: unknown field %q", path, n, k)
		}
	}
	for _, r := range rules {
		if r.match == nil {
			fail("%s: [%s] has no match", path, r.id)
		}
	}
	return rules
}

// readSkipped reads "SKIP <task-id>: why" lines from LOG.md.
func readSkipped(path string) map[string]string {
	out := map[string]string{}
	b, err := os.ReadFile(path)
	if err != nil {
		return out
	}
	for _, l := range strings.Split(string(b), "\n") {
		l = strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(l), "-"))
		if rest, ok := strings.CutPrefix(l, "SKIP "); ok {
			id, why, _ := strings.Cut(rest, ":")
			out[strings.Trim(strings.TrimSpace(id), "`")] = strings.TrimSpace(why)
		}
	}
	return out
}

func printFailures(path string) {
	for _, r := range readRun(path) {
		switch r.Status {
		case "pass":
			fmt.Printf("PASS %s\n", r.Name)
		case "fail", "unreachable":
			fmt.Printf("%s %s (%.0f%% of the way)\n  %s\n", strings.ToUpper(r.Status), r.Name, 100*max(r.Progress, 0), strings.ReplaceAll(clarify(strings.TrimSpace(r.Reason)), "\n", "\n  "))
			if r.After != "" {
				fmt.Printf("  after: %s\n", r.After)
			}
			if r.Screen != "" {
				fmt.Printf("  screen:\n    %s\n", strings.ReplaceAll(strings.TrimRight(r.Screen, "\n"), "\n", "\n    "))
			}
		}
	}
}

var (
	equalMsg = regexp.MustCompile(`Expected '((?s).*)' to equal '((?s).*)'`)
	foundMsg = regexp.MustCompile(`Expected '((?s).*?)' to be found in '((?s).*)'`)
)

// clarify rewrites lazygit's matcher messages, whose argument order differs
// ("Expected <app> to equal <lazygit>" but "Expected <lazygit> to be found in
// <app>"), into one unambiguous form.
func clarify(s string) string {
	s = equalMsg.ReplaceAllString(s, "lazygit wants exactly '$2', the app has '$1'")
	return foundMsg.ReplaceAllString(s, "lazygit wants '$1' in it, the app has '$2'")
}

func firstLine(s string) string {
	s, _, _ = strings.Cut(strings.TrimSpace(s), "\n")
	return s
}

func oneLine(s string, n int) string {
	if len(s) > n {
		return s[:n] + "…"
	}
	return s
}

func check(err error) {
	if err != nil {
		fail("%v", err)
	}
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "tasks: "+format+"\n", args...)
	os.Exit(1)
}
