// Command tooltips writes internal/app/tooltips_gen.go: lazygit's keybinding
// tooltips per context, as i18n field names so they follow the user's
// language. It is its own module because the app doesn't link lazygit's gui.
//
//	cd scripts/tooltips && go run . ../../internal/app/tooltips_gen.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"reflect"
	"slices"

	"github.com/jesseduffield/lazygit/pkg/gui"
	"github.com/jesseduffield/lazygit/pkg/i18n"
)

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: go run . <output.go>")
	}
	fields := map[string]string{} // English text → its first TranslationSet field
	tr := reflect.ValueOf(i18n.EnglishTranslationSet()).Elem()
	for i := range tr.NumField() {
		if f := tr.Field(i); f.Kind() == reflect.String {
			if _, ok := fields[f.String()]; !ok {
				fields[f.String()] = tr.Type().Field(i).Name
			}
		}
	}
	type entry struct{ ctx, label, tip string }
	var entries []entry
	var missed []string
	for _, b := range gui.NewDummyGui().GetCheatsheetKeybindings() {
		if b.Tooltip == "" {
			continue
		}
		tip, ok := fields[b.Tooltip]
		if !ok {
			missed = append(missed, b.ViewName+": "+b.Description)
			continue
		}
		for _, d := range []string{b.Description, b.ShortDescription} {
			if label, ok := fields[d]; ok && d != "" {
				entries = append(entries, entry{b.ViewName, label, tip})
			} else if d == b.Description {
				missed = append(missed, b.ViewName+": "+d)
			}
		}
	}
	slices.SortFunc(entries, func(a, b entry) int {
		return cmpJoin(a.ctx, b.ctx, a.label, b.label, a.tip, b.tip)
	})
	entries = slices.Compact(entries)

	var buf bytes.Buffer
	buf.WriteString("// Code generated by scripts/tooltips; DO NOT EDIT.\n\npackage app\n\n")
	buf.WriteString("// lazygitTooltips is each lazygit context's bindings that have a tooltip:\n")
	buf.WriteString("// the description's and the tooltip's TranslationSet field names.\n")
	buf.WriteString("var lazygitTooltips = map[string][][2]string{\n")
	for i, e := range entries {
		if i == 0 || entries[i-1].ctx != e.ctx {
			if i > 0 {
				buf.WriteString("},\n")
			}
			fmt.Fprintf(&buf, "%q: {\n", e.ctx)
		}
		fmt.Fprintf(&buf, "{%q, %q},\n", e.label, e.tip)
	}
	buf.WriteString("},\n}\n")
	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(os.Args[1], src, 0o644); err != nil {
		log.Fatal(err)
	}
	for _, m := range missed {
		fmt.Fprintln(os.Stderr, "no i18n field for", m)
	}
}

func cmpJoin(pairs ...string) int {
	for i := 0; i < len(pairs); i += 2 {
		if c := bytes.Compare([]byte(pairs[i]), []byte(pairs[i+1])); c != 0 {
			return c
		}
	}
	return 0
}
